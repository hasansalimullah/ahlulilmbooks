export function getRecentBooksByCategory(categoryId: string, limit = 4) {
  return books
    .filter((b) => b.category === categoryId)
    .sort((a, b) => (b.publicationYear || 0) - (a.publicationYear || 0))
    .slice(0, limit)
}

export function getBooksByAuthor(author: string) {
  return books.filter((b) => b.author === author)
}

